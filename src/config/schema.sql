CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(50) PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  name VARCHAR(100) NOT NULL,
  role VARCHAR(50) NOT NULL,
  role_label VARCHAR(100) NOT NULL,
  vacation VARCHAR(50) NOT NULL,
  avatar VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id VARCHAR(50) NOT NULL,
  token VARCHAR(512) NOT NULL UNIQUE,
  expires_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_refresh_tokens_user
    FOREIGN KEY (user_id) REFERENCES users(id)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS person_movements (
  id VARCHAR(50) PRIMARY KEY,
  type VARCHAR(10) NOT NULL,
  person_type VARCHAR(20) NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  badge VARCHAR(50) NOT NULL,
  badge_color VARCHAR(10) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  motif TEXT,
  date VARCHAR(10) NOT NULL,
  time VARCHAR(5) NOT NULL,
  agent VARCHAR(100) NOT NULL,
  linked_to VARCHAR(50)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vehicle_movements (
  id VARCHAR(50) PRIMARY KEY,
  type VARCHAR(10) NOT NULL,
  plate VARCHAR(50) NOT NULL,
  category VARCHAR(20) NOT NULL,
  driver VARCHAR(100) NOT NULL,
  company VARCHAR(100),
  motif TEXT NOT NULL,
  parking_spot VARCHAR(50),
  date VARCHAR(10) NOT NULL,
  time VARCHAR(5) NOT NULL,
  agent VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS logbook_entries (
  id VARCHAR(50) PRIMARY KEY,
  date VARCHAR(10) NOT NULL,
  time VARCHAR(5) NOT NULL,
  category VARCHAR(30) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  description TEXT NOT NULL,
  severity VARCHAR(20) NOT NULL,
  agent VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vacations (
  id VARCHAR(50) PRIMARY KEY,
  date VARCHAR(10) NOT NULL,
  shift VARCHAR(10) NOT NULL,
  outgoing_agent VARCHAR(100) NOT NULL,
  incoming_agent VARCHAR(100) NOT NULL,
  summary TEXT NOT NULL,
  remarks TEXT NOT NULL,
  pending_items TEXT NOT NULL,
  signed_out TINYINT(1) NOT NULL DEFAULT 0,
  signed_in TINYINT(1) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS visitors (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  company VARCHAR(100) NOT NULL,
  motif TEXT NOT NULL,
  badge VARCHAR(50) NOT NULL,
  host_agent VARCHAR(100) NOT NULL,
  arrival VARCHAR(5) NOT NULL,
  expected_duration VARCHAR(50) NOT NULL,
  status VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS consignes (
  id VARCHAR(50) PRIMARY KEY,
  sender VARCHAR(100) NOT NULL,
  text TEXT NOT NULL,
  priority VARCHAR(10) NOT NULL,
  time VARCHAR(50) NOT NULL,
  unread TINYINT(1) NOT NULL DEFAULT 1,
  target VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rondes (
  id VARCHAR(50) PRIMARY KEY,
  circuit VARCHAR(100) NOT NULL,
  start VARCHAR(5) NOT NULL,
  agent VARCHAR(100) NOT NULL,
  status VARCHAR(20) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS checkpoints (
  id VARCHAR(50) PRIMARY KEY,
  ronde_id VARCHAR(50) NOT NULL,
  name VARCHAR(100) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  status VARCHAR(20) NOT NULL,
  time VARCHAR(5),
  CONSTRAINT fk_checkpoints_ronde
    FOREIGN KEY (ronde_id) REFERENCES rondes(id)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notifications (
  id VARCHAR(50) PRIMARY KEY,
  text TEXT NOT NULL,
  time VARCHAR(5) NOT NULL,
  type VARCHAR(10) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS camera_feeds (
  id VARCHAR(50) PRIMARY KEY,
  label VARCHAR(100) NOT NULL,
  status VARCHAR(10) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS camera_extractions (
  id VARCHAR(50) PRIMARY KEY,
  camera_id VARCHAR(50) NOT NULL,
  camera_label VARCHAR(100) NOT NULL,
  requested_by VARCHAR(100) NOT NULL,
  requested_at VARCHAR(16) NOT NULL,
  start_time VARCHAR(16) NOT NULL,
  end_time VARCHAR(16) NOT NULL,
  reason TEXT NOT NULL,
  status VARCHAR(20) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_camera_extractions_camera
    FOREIGN KEY (camera_id) REFERENCES camera_feeds(id)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS access_logs (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  badge VARCHAR(50) NOT NULL,
  type VARCHAR(20) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  time VARCHAR(5) NOT NULL,
  detail TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
